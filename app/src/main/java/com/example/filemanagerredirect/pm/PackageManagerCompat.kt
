package com.example.filemanagerredirect.pm

import android.content.pm.PackageInfo
import android.content.pm.PackageManager
import android.content.pm.VersionedPackage
import android.os.Build

/**
 * Safe wrapper for getPackageInfo across API levels.
 * Returns null if the package isn't found or any error occurs.
 */
fun PackageManager.getPackageInfoCompat(packageName: String, flags: Int = 0): PackageInfo? {
    return try {
        if (Build.VERSION.SDK_INT >= 33) {
            // On Tiramisu+ you’re expected to use VersionedPackage + flags object
            @Suppress("DEPRECATION")
            getPackageInfo(
                VersionedPackage(packageName, 0),
                PackageManager.PackageInfoFlags.of(flags.toLong())
            )
        } else {
            @Suppress("DEPRECATION")
            getPackageInfo(packageName, flags)
        }
    } catch (_: Throwable) {
        null
    }
}